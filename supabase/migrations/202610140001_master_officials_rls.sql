-- CivicPie master civic-data schema + RLS.
--
-- 1. Creates the master tables the Next.js data layer (src/lib/civic/db.ts)
--    queries: sources, offices, districts, officials, candidates, agencies,
--    contact_points. Every statement is `if not exists` so this is safe to run
--    on a database that already has the master schema from civicpie-data.
-- 2. Closes an RLS gap in the initial migration: community_subscriptions holds
--    subscriber emails/addresses and had no RLS at all.
--
-- Access model: public civic reference data is world-readable; there are NO
-- insert/update/delete policies, so only the service role (which bypasses
-- RLS) and direct DB connections can write. Operational tables
-- (scrape_runs, reconcile_diffs) and PII (community_subscriptions) get RLS
-- with no policy = denied to anon/authenticated.

create table if not exists public.sources (
  source_id text primary key,
  name text not null,
  url text,
  source_type text,
  license text,
  notes text,
  retrieved_at timestamptz,
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.offices (
  office_id text primary key,
  title text not null,
  level text not null check (level in ('federal', 'state', 'local')),
  branch text check (branch in ('legislative', 'executive', 'judicial')),
  term_length_years integer,
  is_elected boolean not null default true
);

create table if not exists public.districts (
  district_id text primary key,
  district_type text not null,
  district_name text not null,
  district_number text,
  city text,
  state_abbr text,
  source_id text references public.sources(source_id),
  external_refs jsonb not null default '{}'::jsonb
);

create table if not exists public.officials (
  official_id bigint generated by default as identity primary key,
  office_id text not null references public.offices(office_id),
  district_id text references public.districts(district_id),
  full_name text not null,
  first_name text,
  last_name text,
  party text,
  is_incumbent boolean not null default true,
  term_start date,
  term_end date,
  photo_url text,
  biography text,
  source_id text references public.sources(source_id),
  source_key text unique,
  external_ids jsonb not null default '{}'::jsonb,
  social jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.candidates (
  candidate_id bigint generated by default as identity primary key,
  office_id text not null references public.offices(office_id),
  district_id text references public.districts(district_id),
  state_abbr text,
  full_name text not null,
  party text,
  election_year integer,
  election_date date,
  is_incumbent boolean not null default false,
  source_id text references public.sources(source_id),
  source_key text unique,
  external_ids jsonb not null default '{}'::jsonb
);

create table if not exists public.agencies (
  agency_id bigint generated by default as identity primary key,
  name text not null,
  level text,
  agency_type text,
  parent_agency_id bigint references public.agencies(agency_id),
  description text,
  website text,
  city text,
  state_abbr text,
  source_id text references public.sources(source_id),
  source_key text unique,
  external_refs jsonb not null default '{}'::jsonb
);

create table if not exists public.contact_points (
  contact_id bigint generated by default as identity primary key,
  official_id bigint references public.officials(official_id) on delete cascade,
  agency_id bigint references public.agencies(agency_id) on delete cascade,
  kind text not null,
  label text,
  value text not null,
  is_primary boolean not null default false,
  source_id text references public.sources(source_id),
  check (official_id is not null or agency_id is not null)
);

-- Hot-path indexes (search by district, office, name, state, level).
create index if not exists idx_districts_type_state on public.districts (district_type, state_abbr);
create index if not exists idx_districts_city on public.districts (city);
create index if not exists idx_officials_office on public.officials (office_id);
create index if not exists idx_officials_district on public.officials (district_id);
create index if not exists idx_officials_name on public.officials (lower(full_name));
create index if not exists idx_candidates_district on public.candidates (district_id);
create index if not exists idx_candidates_office on public.candidates (office_id);
create index if not exists idx_agencies_level on public.agencies (level);
create index if not exists idx_agencies_parent on public.agencies (parent_agency_id);
create index if not exists idx_contact_points_official on public.contact_points (official_id);
create index if not exists idx_contact_points_agency on public.contact_points (agency_id);

drop trigger if exists trg_officials_updated_at on public.officials;
create trigger trg_officials_updated_at
before update on public.officials
for each row execute function public.set_updated_at();

-- RLS: public read on reference data -------------------------------------
do $$
declare
  t text;
begin
  foreach t in array array[
    'sources', 'offices', 'districts', 'officials', 'candidates',
    'agencies', 'contact_points', 'civic_sources', 'civic_items'
  ]
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "public read" on public.%I', t);
    execute format(
      'create policy "public read" on public.%I for select to anon, authenticated using (true)', t
    );
  end loop;

  -- Deny-by-default (RLS on, no policy): PII and operational tables.
  foreach t in array array['community_subscriptions', 'scrape_runs', 'reconcile_diffs']
  loop
    execute format('alter table public.%I enable row level security', t);
  end loop;
end
$$;
