"""Probe candidate Tier 2/3 source pages with a real browser to plan scrapers.

For each URL records: HTTP status, whether the content is JS-rendered (rendered
text much longer than the raw HTML text), count of mailto:/tel: links (a cheap
proxy for "has parseable officials contact data"), and robots.txt permission.
Output: a markdown table (docs/TIER2_SOURCE_PROBE.md).

    python -m backend.qa.probe_sources > docs/TIER2_SOURCE_PROBE.md
"""

from __future__ import annotations

import re
import sys
import urllib.robotparser
from urllib.parse import urlparse

import httpx

from backend.qa.browser import UA, playwright_fetch

CANDIDATES = [
    ("county", "Cook County IL - Board of Commissioners", "https://www.cookcountyil.gov/agency/board-commissioners"),
    ("county", "Harris County TX - Commissioners Court", "https://www.harriscountytx.gov/Government/Elected-Officials"),
    ("county", "Los Angeles County - Board of Supervisors", "https://bos.lacounty.gov/"),
    ("county", "Maricopa County AZ - Board of Supervisors", "https://www.maricopa.gov/5645/Board-of-Supervisors"),
    ("county", "King County WA - Council", "https://kingcounty.gov/en/legacy/council"),
    ("city", "Houston TX - City Council", "https://www.houstontx.gov/council/"),
    ("city", "Phoenix AZ - City Council", "https://www.phoenix.gov/mayorcouncil"),
    ("city", "Philadelphia PA - City Council", "https://phlcouncil.com/council-members/"),
    ("city", "San Antonio TX - City Council", "https://www.sanantonio.gov/Council"),
    ("city", "Seattle WA - City Council", "https://www.seattle.gov/council"),
    ("aggregator", "NACo county officials", "https://www.naco.org/resources/county-officials"),
    ("state", "Illinois State Board of Elections", "https://www.elections.il.gov/"),
    ("school", "CPS Chicago Board of Education", "https://www.cps.edu/about/board-of-education/"),
]


def robots_ok(url: str) -> str:
    u = urlparse(url)
    try:
        r = httpx.get(f"{u.scheme}://{u.netloc}/robots.txt", timeout=10, headers={"User-Agent": UA}, follow_redirects=True)
        if r.status_code != 200:
            return f"no robots ({r.status_code})"
        rp = urllib.robotparser.RobotFileParser()
        rp.parse(r.text.splitlines())
        return "allowed" if rp.can_fetch(UA, url) else "DISALLOWED"
    except Exception:
        return "robots unreachable"


def static_text_len(url: str) -> int | None:
    try:
        r = httpx.get(url, timeout=15, headers={"User-Agent": UA}, follow_redirects=True)
        html = re.sub(r"(?is)<(script|style).*?</\\1>", " ", r.text)
        return len(re.sub(r"\\s+", " ", re.sub(r"<[^>]+>", " ", html)).strip())
    except Exception:
        return None


def main() -> None:
    print("# Tier 2/3 source probe\n")
    print("Generated by `python -m backend.qa.probe_sources` (Playwright/Chromium). "
          "`JS-rendered` = rendered text > 3x the static HTML text.\n")
    print("| Tier | Source | HTTP | robots | JS-rendered | mailto | tel | links | Verdict |")
    print("|---|---|---|---|---|---|---|---|---|")
    for tier, name, url in CANDIDATES:
        pg = playwright_fetch(url)
        rob = robots_ok(url)
        if pg.error:
            print(f"| {tier} | [{name}]({url}) | - | {rob} | - | - | - | - | unreachable: {pg.error[:60]} |")
            continue
        st = static_text_len(url)
        rendered = len(pg.text)
        js = "yes" if st is not None and rendered > 3 * max(st, 1) else ("no" if st is not None else "?")
        if rob == "DISALLOWED":
            verdict = "skip (robots)"
        elif pg.status == 404:
            verdict = "dead URL - find current page"
        elif pg.status and pg.status >= 400:
            verdict = f"HTTP {pg.status} - retry/blocked?"
        elif js == "yes":
            verdict = "needs browser scrape"
        elif pg.mailto + pg.tel >= 3:
            verdict = "static scrape, contacts on page"
        else:
            verdict = "static scrape, contacts on subpages"
        print(f"| {tier} | [{name}]({url}) | {pg.status} | {rob} | {js} | {pg.mailto} | {pg.tel} | {pg.links} | {verdict} |")
    print("\nVerdicts are heuristics for planning, not a guarantee a scraper will parse cleanly.")


if __name__ == "__main__":
    sys.exit(main())
